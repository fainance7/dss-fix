// Названия районов СКО в предложном падеже для заголовков графиков:
// «Динамика … в Айыртауском районе, 2003–2025 гг.» (замечание заказчика).
// В БД названия хранятся в именительном падеже.

/** «в Айыртауском районе», «в г. Петропавловске», «в районе имени Габита Мусрепова». */
export function inRegion(name: string): string {
  const n = name.trim()
  let m = n.match(/^(.+?)ий район$/i)
  if (m) return `в ${m[1]}ом районе`
  m = n.match(/^Район\s+им\.?\s*(.+)$/i)
  if (m) return `в районе имени ${m[1].trim()}`
  m = n.match(/^Район\s+(.+)$/i)
  if (m) return `в районе ${m[1].trim()}`
  m = n.match(/^г\.\s*(.+)$/)
  if (m) return `в г. ${m[1].trim()}е`
  m = n.match(/^(.+?)ая область$/i)
  if (m) return `в ${m[1]}ой области`
  return `— ${n}`
}
