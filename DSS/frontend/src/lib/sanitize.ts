// sanitize.ts — client-side HTML/SVG sanitization (audit H-2/H-3).
//
// Defense-in-depth: the backend already strips raw HTML blocks and filters
// href/src URLs before returning markdown-rendered HTML, and the SVG marker
// strings are built from internal data. DOMPurify is the second layer: it
// guarantees that no <script>, event handler, javascript: URL, or other
// executable content survives injection into the DOM, regardless of source.
//
// SSR note: DOMPurify requires window. All call sites are client-side
// ('use client' components or map marker effect hooks), so the SSR fallback
// (return '') is only reachable in test/edge cases.

import DOMPurify, { type Config } from 'dompurify'

// Base config for HTML content (protocol page markdown output).
const HTML_CONFIG: Config = {
  // Allow standard safe content from the markdown pipeline.
  ADD_ATTR: ['target'], // <a target="_blank"> is generated by markdown links
}

// Config for the SVG marker strings (donut / pie / bar charts injected into
// maplibre marker elements). Keeps the SVG element family and the presentation
// attributes the chart builders emit; strips everything executable.
const SVG_CONFIG: Config = {
  ADD_TAGS: [
    'svg', 'g', 'path', 'circle', 'ellipse', 'rect', 'line', 'polyline',
    'polygon', 'text', 'tspan', 'defs', 'linearGradient', 'stop', 'use',
  ],
  ADD_ATTR: [
    'd', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'y1', 'x2', 'y2',
    'points', 'width', 'height', 'viewBox', 'fill', 'fill-opacity',
    'stroke', 'stroke-width', 'stroke-dasharray', 'stroke-dashoffset',
    'stroke-linecap', 'stroke-linejoin', 'opacity', 'transform', 'style',
    'xmlns', 'href',
  ],
}

function purify(): typeof DOMPurify | null {
  if (typeof window === 'undefined') return null
  return DOMPurify(window)
}

/**
 * Sanitize an HTML string (markdown-rendered protocol page).
 * Returns '' when the browser environment is unavailable so the UI degrades
 * to "no content" rather than injecting raw markup.
 */
export function sanitizeHtml(html: string | null | undefined): string {
  if (!html) return ''
  const d = purify()
  if (!d) return ''
  return d.sanitize(html, HTML_CONFIG) as string
}

/**
 * Sanitize an SVG string destined for el.innerHTML (map markers).
 * Returns '' when the browser environment is unavailable.
 */
export function sanitizeSvg(svg: string | null | undefined): string {
  if (!svg) return ''
  const d = purify()
  if (!d) return ''
  return d.sanitize(svg, SVG_CONFIG) as string
}
