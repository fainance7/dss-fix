    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)

    make_title_page(doc)
    make_toc(doc)
    for fn in (s1, s2, s3, s4, s5, s6, s7, s8, s9, s10):
        fn(doc)

    doc.save(OUTPUT)
    print(f"Saved: {OUTPUT}  ({OUTPUT.stat().st_size:,} bytes)")


