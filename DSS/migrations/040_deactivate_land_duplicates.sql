-- Migration 040: деактивация пустых дублей показателей направления «land».
-- Заведены в 015, данных нет ни в одной таблице; значения лежат в показателях «Площадь …»:
--   Пашня → Площадь пашни, Пастбища → Площадь пастбищ, Земли запаса → Площадь земель запаса,
--   Земли водного фонда / лесного фонда / населённых пунктов → Площадь земель ….
-- Не удаляем: строки остаются, intake-portal отклоняет неактивные показатели.
-- Идемпотентно.

BEGIN;

UPDATE indicators i
SET is_active = FALSE
FROM directions d
WHERE d.id = i.direction_id
  AND d.code = 'land'
  AND i.is_active
  AND i.name IN ('Пашня', 'Пастбища', 'Земли запаса',
                 'Земли водного фонда', 'Земли лесного фонда', 'Земли населённых пунктов')
  AND NOT EXISTS (SELECT 1 FROM indicator_values v WHERE v.indicator_id = i.id);

COMMIT;
