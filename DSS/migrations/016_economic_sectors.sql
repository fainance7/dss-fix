-- 016_economic_sectors.sql
-- Справочник секторов экономики (ОКЭД, разделы A–S) для отображения на
-- дашбордах. Используется как единый источник правды:
--   * смежная команда берёт `indicator_name` для наименования показателей
--     «Среднемесячная номинальная заработная плата — <сектор>»;
--   * дашборды берут short_name / color / sort_order для отрисовки серий.
-- Справочник не суммируется: ЗП — средняя величина. «Промышленность» (B–E) —
-- агрегат под-секторов B/C/D/E (is_aggregate=true), хранится для совместимости
-- с исходным листом, но не должен складываться с под-секторами.

CREATE TABLE IF NOT EXISTS economic_sectors (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    oked_code      VARCHAR(8)   NOT NULL,                    -- раздел ОКЭД (A..S, B-E)
    name           VARCHAR(300) NOT NULL UNIQUE,             -- полное имя сектора (как в источнике)
    short_name     VARCHAR(80)  NOT NULL,                    -- короткая подпись для графиков
    indicator_name VARCHAR(300) NOT NULL UNIQUE,             -- имя показателя ЗП в каталоге indicators
    color          VARCHAR(7)   NOT NULL,                    -- #RRGGBB
    is_aggregate   BOOLEAN      NOT NULL DEFAULT FALSE,       -- true только для «Промышленность» (B–E)
    parent_code    VARCHAR(8),                               -- ОКЭД родителя-агрегата (для B/C/D/E → 'B-E')
    sort_order     INTEGER      NOT NULL DEFAULT 0,
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

