-- Migration 023: исправления климатического раздела по замечаниям заказчика
-- (docs/dashboards/climate/Замечания по климатическому разделу дашборда.docx).
--
-- 1. Научно корректные единицы измерения:
--    • «безразм.» → «безразмерная величина» (строку units делят ТОЛЬКО климатические
--      K и ГТК — проверено, переименование безопасно).
--    • Сумма активных температур измеряется в °C·сут (градусо-сутки), а не в °C.
--      Строку «°C» делят 5 температурных показателей, поэтому создаём отдельную
--      единицу «°C·сут» и переназначаем её только показателям суммы активных температур.
--
-- 2. Честное переименование показателей «Доля площади с …»: фактически значения
--    выведены из данных метеостанций района (доля станций), а не из растрового/
--    попиксельного распределения площади. Заголовок «доля площади» методически
--    некорректен (см. замечание 2.2: постоянные 100 % по K<0,80 и ГТК<0,80).
--    Растровых данных в системе нет — переименовываем в «Доля метеостанций района…»,
--    единица «%» остаётся корректной.
--
-- Идемпотентно. Применять на dev (dss-postgres :5433) и на проде (dss_db).

BEGIN;

-- ── 1a. безразм. → безразмерная величина ─────────────────────────────────────
UPDATE units
   SET name = 'безразмерная величина'
 WHERE name = 'безразм.';

-- ── 1b. Новая единица °C·сут для суммы активных температур ────────────────────
INSERT INTO units (name, description)
VALUES ('°C·сут', 'Градусо-сутки (сумма активных температур)')
ON CONFLICT (name) DO NOTHING;

UPDATE indicators i
   SET unit_id = (SELECT id FROM units WHERE name = '°C·сут')
 WHERE i.name IN (
        'Сумма активных температур >10°C (Σt)',
        'Сумма активных температур выше 10°C'
      );

-- ── 2. Честное переименование показателей «Доля площади …» ────────────────────
UPDATE indicators
   SET name = 'Доля метеостанций района с K<0,80 (риск дефицита влаги)'
 WHERE name = 'Доля площади с K<0.80 (риск дефицита влаги)';

UPDATE indicators
   SET name = 'Доля метеостанций района с ГТК<0,80'
 WHERE name = 'Доля площади с ГТК<0.80';

UPDATE indicators
   SET name = 'Доля метеостанций района с суммой активных температур <2300 °C·сут'
 WHERE name = 'Доля площади с Σt<2300°C';

UPDATE indicators
   SET name = 'Доля метеостанций района с продолжительностью вегетационного периода <140 сут.'
 WHERE name = 'Доля площади с вегет. периодом <140 сут';

COMMIT;
