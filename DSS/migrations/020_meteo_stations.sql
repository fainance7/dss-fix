-- Migration 020: справочник метеостанций СКО (станция → район + координаты)
-- Метеостанций как сущности в DSS не было; данные климата агрегированы по
-- районам (indicator_values). Этот справочник нужен для точечного слоя станций
-- на карте и явной привязки станция→район. 19 станций по списку заказчика;
-- координаты (WGS84) из reports_db (таблица «метеостанции_и_агрометпос»);
-- у Благовещенки координат в источнике нет (NULL, заполнить позже).
-- Идемпотентно (IF NOT EXISTS / ON CONFLICT) — применяется на каждом деплое.

BEGIN;

CREATE TABLE IF NOT EXISTS meteo_stations (
    id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name       VARCHAR(120) NOT NULL UNIQUE,
    region_id  UUID NOT NULL REFERENCES regions(id) ON DELETE RESTRICT,  -- район СКО
    kato_code  VARCHAR(9),                 -- связь с н.п. в kato_reference (опц., NULL)
    lat        DOUBLE PRECISION,           -- WGS84, опц.
    lon        DOUBLE PRECISION,           -- WGS84, опц.
    is_active  BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_meteo_stations_region ON meteo_stations (region_id);

-- Исправление опечатки в названии станции (было «Новоишинский») — до сидинга,
-- иначе ON CONFLICT (name) не сработает и станция задвоится.
UPDATE meteo_stations SET name = 'Новоишимский'
 WHERE name = 'Новоишинский' AND NOT EXISTS (SELECT 1 FROM meteo_stations WHERE name = 'Новоишимский');

