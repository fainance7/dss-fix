-- Migration 036: годовые и сезонные климатические показатели по метеостанциям.
--
-- Годовые ряды температуры и осадков считает Система из месяцев районов
-- («… (по метеостанциям)», см. 033) — app/services/climate_dekads.recompute_yearly:
--   среднегодовая температура — среднее 12 месяцев;
--   осадки за год (1–12), вегетационный период (5–8), весну (4–5), осень (9–10),
--   холодный период (ноябрь–декабрь прошлого года + январь–март).
-- Прежние значения (реанализ Open-Meteo) переносятся в indicator_values_archive
-- скриптом scripts/import_climate_workbook.py / recompute_yearly.
-- ΣT(5-8) — сумма активных температур выше 10 °C за май–август по станциям
-- из файла заказчика (столбец ΣT_05_08), значение района — среднее станций.
-- Идемпотентно.

BEGIN;

INSERT INTO indicators (direction_id, unit_id, name, sort_order, is_active)
SELECT d.id, u.id, v.name, 0, TRUE
FROM (VALUES ('Сумма активных температур воздуха выше 10 °C за май–август, ΣT(5-8)', '°C·сут'),
             ('Сумма осадков за весенний период (апрель–май)', 'мм'),
             ('Сумма осадков за осенний период (сентябрь–октябрь)', 'мм')) AS v(name, unit)
JOIN directions d ON d.code = 'climate'
JOIN units u ON u.name = v.unit
ON CONFLICT (direction_id, name) DO NOTHING;

-- Расчётные показатели: ручной ввод и приём через intake для них запрещены.
UPDATE indicators SET is_computed = TRUE
 WHERE direction_id = (SELECT id FROM directions WHERE code = 'climate')
   AND name IN ('Среднегодовая температура воздуха', 'Годовая сумма осадков',
                'Сумма осадков за вегетационный период', 'Сумма осадков за холодный период',
                'Сумма осадков за весенний период (апрель–май)',
                'Сумма осадков за осенний период (сентябрь–октябрь)');

COMMIT;
