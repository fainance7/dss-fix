def gtk_class(v: float) -> str:
    """Градации засушливости по ГТК(5-8) (шкала эксперта)."""
    v = round(v, 2)
    if v <= 0.50:
        return "сильно засушливо"
    if v <= 0.80:
        return "умеренно засушливо"
    if v <= 1.00:
        return "слабо засушливо"
    if v <= 2.00:
        return "достаточное увлажнение"
    return "избыточное увлажнение"


